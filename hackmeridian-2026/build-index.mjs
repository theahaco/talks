// Joins intro.html, scaffold.html, registry.html, nido.html and outro.html into index.html, one deck for the joint session.
// Run after editing any of them: node build-index.mjs
import { readFileSync, writeFileSync } from "node:fs";

const open = '<div class="reveal"><div class="slides">';
const close = "</div></div>";
const slides = (file) => {
  const html = readFileSync(new URL(file, import.meta.url), "utf8");
  return html.slice(html.indexOf(open) + open.length, html.indexOf(close));
};

const shell = readFileSync(new URL("scaffold.html", import.meta.url), "utf8");
const out = shell
  .replace("<!doctype html>", "<!doctype html>\n<!-- Generated by build-index.mjs from intro.html + scaffold.html + registry.html + nido.html + outro.html. Don't edit. -->")
  .replace("<title>Stellar Scaffold</title>", "<title>Scaffold. Register. Nido.</title>")
  .replace(
    open + slides("scaffold.html") + close,
    open + slides("intro.html") + "\n<!-- ===== Scaffold ===== -->\n" + slides("scaffold.html") + "\n<!-- ===== Registry ===== -->\n" + slides("registry.html") + "\n<!-- ===== Nido ===== -->\n" + slides("nido.html") + "\n<!-- ===== Closing ===== -->\n" + slides("outro.html") + close,
  );

writeFileSync(new URL("index.html", import.meta.url), out);
console.log("wrote index.html");
